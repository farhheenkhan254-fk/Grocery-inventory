def build_inventory_report_blocks(products: List[Dict[str, Any]], active_orders: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Constructs an executive inventory health report for #inventory-reports.
    """
    total_items = len(products)
    low_stock_count = sum(1 for p in products if p.get("is_low_stock") or (p.get("current_stock", 0) <= p.get("minimum_stock", 0)))
    active_po_count = len(active_orders)

    lines = []
    for p in products:
        status_icon = "🔴" if p.get("current_stock", 0) <= p.get("minimum_stock", 0) else "🟢"
        lines.append(f"{status_icon} *{p['name']}*: {p['current_stock']} {p['unit']} (Threshold: {p['minimum_stock']} {p['unit']})")

    blocks = [
        {
            "type": "header",
            "text": {"type": "plain_text", "text": "📊 Daily Grocery Inventory & Procurement Report", "emoji": True}
        },
        {
            "type": "section",
            "fields": [
                {"type": "mrkdwn", "text": f"*Total SKUs:*\n{total_items}"},
                {"type": "mrkdwn", "text": f"*Items Below Threshold:*\n*{low_stock_count}*"},
                {"type": "mrkdwn", "text": f"*Active Purchase Orders:*\n{active_po_count}"},
                {"type": "mrkdwn", "text": "*System Status:*\nHealthy / Monitoring Active"}
            ]
        },
        {"type": "divider"},
        {
            "type": "section",
            "text": {"type": "mrkdwn", "text": "*Current Stock Levels:*\n" + "\n".join(lines)}
        },
        {
            "type": "context",
            "elements": [
                {"type": "mrkdwn", "text": "🤖 Generated by *Supervisor Agent* & *Notification Agent*"}
            ]
        }
    ]
    fallback = f"📊 Daily Inventory Report: {low_stock_count}/{total_items} items low stock. {active_po_count} active orders."
    return {"text": fallback, "blocks": blocks}

def build_status_update_blocks(title: str, message: str, channel: str) -> Dict[str, Any]:
    blocks = [
        {
            "type": "section",
            "text": {"type": "mrkdwn", "text": f"*{title}*\n{message}"}
        }
    ]
    return {"text": f"{title}: {message}", "blocks": blocks}
